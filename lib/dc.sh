# Sourced by build.sh: the DC VM (Windows Server, AD DS, AD CS).
# shellcheck shell=bash

dc_iso() {
    need_secrets ADMIN_PW DSRM_PW LAB_USER_PW JOIN_PW
    [[ "$ADMIN_PW" != *[[:space:]]* ]] || die "ADMIN_PW must not contain white space (schtasks /rp argument)"
    local d="$STAGE/dc-iso"
    rm -rf "$d"; mkdir -p "$d/provision"

    log "rendering autounattend.xml"
    VM_HOSTNAME="$DC_HOSTNAME" OWNER="$REGISTERED_OWNER" TZ="$GUEST_TZ" IMAGE_INDEX="$WIN_IMAGE_INDEX" \
        render dc/autounattend.xml.tmpl "$d/autounattend.xml" xml

    log "rendering provision/config.ps1"
    local ntp; read -ra ntp <<<"${NTP_SERVERS-}"
    # Windows PowerShell 5.1 reads a .ps1 without a BOM as ANSI.
    printf '\xEF\xBB\xBF' > "$d/provision/config.ps1"
    cat >> "$d/provision/config.ps1" <<EOF
# Generated by build.sh from lab.env. Do not edit the copy on the VM.
\$Cfg = @{
    Work          = $(ps_str "$GUEST_WORK")
    Domain        = $(ps_str "$DOMAIN")
    Netbios       = $(ps_str "$NETBIOS")
    AdLevel       = $(ps_str "$AD_LEVEL")
    AdminPw       = $(ps_str "$ADMIN_PW")
    DsrmPw        = $(ps_str "$DSRM_PW")
    DcIp          = $(ps_str "$DC_IP")
    NetPrefix     = $NET_PREFIX
    NetGw         = $(ps_str "$NET_GW")
    NetworkId     = $(ps_str "$NETWORK_ID")
    ReverseZone   = $(ps_str "$REVERSE_ZONE")
    DnsForwarders = $(ps_array "$NET_GW")
    NtpServers    = $(ps_array "${ntp[@]}")
    LabUsers      = $(ps_array "${LAB_USER_LIST[@]}")
    LabUserPw     = $(ps_str "$LAB_USER_PW")
    LinuxGroup    = $(ps_str "$LINUX_GROUP")
    JoinUser      = $(ps_str "$JOIN_USER")
    JoinPw        = $(ps_str "$JOIN_PW")
    SmbEncrypt    = ${SMB_ENCRYPT:-1}
    HomesPath     = 'C:\Homes'
    CaName        = $(ps_str "$CA_NAME")
}
EOF
    local f
    for f in dc/provision/*.ps1; do
        printf '\xEF\xBB\xBF' > "$d/provision/$(basename "$f")"
        cat "$f" >> "$d/provision/$(basename "$f")"
    done
    genisoimage -quiet -J -r -V PROVISION -o "$STAGE/dc-provision.iso" "$d"
    log "dc-provision.iso ready ($(du -h "$STAGE/dc-provision.iso" | cut -f1))"
    iso_stamp dc
}

dc_vm() {
    require_qemu_access
    pool_refresh
    vm_exists "$DC_VM" && die "VM '$DC_VM' exists: ./build.sh dc destroy first"
    require_no_orphan_disk "$DC_VM"
    require_nocow "$DC_VM"
    if ! iso_current dc "$STAGE/dc-provision.iso"; then
        log "dc-provision.iso missing or older than its inputs: building it"
        dc_iso
    fi
    log "creating $DC_VM (${DC_VCPUS} vCPU, ${DC_RAM_MB} MB, ${DC_DISK_GB} GB, SeaBIOS)"
    # clock offset=utc: Kerberos rejects more than 5 min skew between the client and the DC.
    # The install config has on_reboot=destroy. --wait keeps virt-install until the first Setup reboot,
    # then virt-install starts the final config (boot=hd).
    virt-install \
        --connect "$LIBVIRT_URI" \
        --name "$DC_VM" \
        --vcpus "$DC_VCPUS" \
        --memory "$DC_RAM_MB" \
        --cpu host-passthrough \
        --disk "pool=$POOL,size=$DC_DISK_GB,bus=virtio,format=qcow2,driver.cache=none,driver.io=native,driver.discard=unmap" \
        --network "network=$NET,model=virtio" \
        --cdrom "$WINSERVER_ISO" \
        --disk "path=$VIRTIO_ISO,device=cdrom,readonly=on" \
        --disk "path=$STAGE/dc-provision.iso,device=cdrom,readonly=on" \
        --os-variant "${DC_OS_VARIANT:-win2k25}" \
        --clock offset=utc \
        --graphics vnc,listen=127.0.0.1 \
        --channel unix,target.type=virtio,target.name=org.qemu.guest_agent.0 \
        --panic model=hyperv \
        --events on_crash=destroy \
        --noautoconsole \
        --wait 40
    "${VIRSH[@]}" autostart "$DC_VM" >/dev/null
    # A WinPE that stops early leaves a small disk, and the next boot fails at \Boot\BCD.
    local alloc
    alloc=$("${VIRSH[@]}" domblkinfo "$DC_VM" vda | awk '/^Allocation:/ { print $2 }')
    if [ "${alloc:-0}" -lt $(( 6 * 1024 * 1024 * 1024 )) ]; then
        die "WinPE stopped early: only $(( ${alloc:-0} / 1024 / 1024 )) MiB on the disk. Check: ./build.sh dc screenshot"
    fi
    "${VIRSH[@]}" domstate "$DC_VM" | grep -q running || die "$DC_VM is not running after the Setup reboot"
    log "Windows Setup passed its first reboot. Next: ./build.sh dc wait"
}

dc_start() {
    require_qemu_access
    "${VIRSH[@]}" domstate "$DC_VM" | grep -q 'shut off' || die "$DC_VM is not shut off"
    "${VIRSH[@]}" start "$DC_VM" >/dev/null
    log "$DC_VM started. AD and DNS answer after approximately 1 min (./build.sh dc phase)"
}

dc_status() {
    GUEST_EXEC_TIMEOUT=30 guest_run dc dc/guest/status.ps1 "Work=$GUEST_WORK" 2>/dev/null
}

dc_phase_name() {
    case "$1" in
        "") echo "0: not started (resume task)" ;;
        1) echo "1: static IP, AD DS forest $DOMAIN" ;;
        2) echo "2: DNS, NTP, OUs, users, join account" ;;
        3) echo "3: file server, Homes\$ share" ;;
        4) echo "4: WinRM, RDP" ;;
        5) echo "5: export identity" ;;
        6) echo "6: AD CS enterprise CA, web enrollment" ;;
        7) echo "7: autoenrollment templates MLD-LinuxComputer, MLD-LinuxUser" ;;
        *) echo "$1" ;;
    esac
}

dc_phase() {
    local s
    s=$(dc_status) || { echo "guest agent not reachable (Setup running or VM rebooting)"; return 0; }
    if [ -n "$(json_get failed <<<"$s")" ]; then echo "FAILED: $(json_get failed <<<"$s")"; return 0; fi
    if [ -n "$(json_get "done" <<<"$s")" ]; then echo "DONE ($(json_get "done" <<<"$s"))"; return 0; fi
    dc_phase_name "$(json_get phase <<<"$s")"
}

dc_log() { ./guest-exec.sh dc "Get-Content '$GUEST_WORK\\provision.log' -Tail ${1:-60}"; }

dc_skew() {
    local s; s=$(dc_status) || return 1
    local skew=$(( $(json_get utc <<<"$s") - $(date -u +%s) ))
    echo "${skew#-}"
}

dc_wait() {
    local deadline=$(( $(date +%s) + 2*60*60 )) last="unset" s phase failed done_at skew
    log "waiting for DC provisioning (up to 2 h)"
    while [ "$(date +%s)" -lt "$deadline" ]; do
        if "${VIRSH[@]}" domstate "$DC_VM" --reason 2>/dev/null | grep -q crashed; then
            die "DC crashed (bluescreen). Stop code: sudo grep 'panic hyper-v' /var/log/libvirt/qemu/$DC_VM.log | tail -1"
        fi
        if "${VIRSH[@]}" domstate "$DC_VM" 2>/dev/null | grep -q 'shut off'; then
            warn "DC is shut off during provisioning: starting it"
            "${VIRSH[@]}" start "$DC_VM" >/dev/null 2>&1 || true
        fi
        if s=$(dc_status); then
            failed=$(json_get failed <<<"$s")
            if [ -n "$failed" ]; then
                warn "provisioning FAILED: $failed"
                dc_log 40 || true
                die "fix the cause, then ./build.sh dc resume (or dc destroy + dc vm)"
            fi
            done_at=$(json_get "done" <<<"$s")
            if [ -n "$done_at" ]; then
                skew=$(( $(json_get utc <<<"$s") - $(date -u +%s) )); skew=${skew#-}
                [ "$skew" -le 60 ] || die "DC clock is ${skew}s off host UTC: Kerberos rejects more than 300s"
                log "DC provisioning DONE at $done_at (clock skew ${skew}s)"
                ./guest-exec.sh dc "Get-Content '$GUEST_WORK\\timing.log'" 2>/dev/null | sed 's/^/  /' || true
                return 0
            fi
            phase=$(json_get phase <<<"$s")
            if [ "$phase" != "$last" ]; then printf '\n'; log "phase $(dc_phase_name "$phase")"; last="$phase"; fi
        fi
        printf '.'
        sleep 30
    done
    die "timed out. Check ./build.sh dc screenshot and ./build.sh dc log"
}

# The provisioning marker is there before AD DS answers after a boot. Get-ADDomain waits for AD DS.
dc_ready() {
    local i
    vm_exists "$DC_VM" || die "no VM '$DC_VM': ./build.sh dc vm first (about 1 h)"
    vm_running "$DC_VM" || dc_start
    dc_wait
    for i in $(seq 20); do
        GUEST_EXEC_TIMEOUT=30 ./guest-exec.sh dc 'Get-ADDomain | Out-Null' >/dev/null 2>&1 && return 0
        [ "$i" -gt 1 ] || log "waiting for AD DS on $DC_VM"
        sleep 15
    done
    die "AD DS on $DC_VM does not answer after 5 min: ./build.sh dc screenshot"
}

# For a fix after FAILED. config.ps1 stays as rendered at build time.
dc_resume() {
    local f from="${1:-}"
    # config.ps1 comes from the current lab.env (passwords can have changed: dc set-passwords).
    dc_iso >/dev/null
    for f in dc/provision/*.ps1 "$STAGE/dc-iso/provision/config.ps1"; do
        guest_run dc dc/guest/push-file.ps1 "Path=$GUEST_WORK\\provision\\$(basename "$f")" "B64=$(base64 -w0 "$f")" \
            || die "could not copy $f into the guest"
        log "pushed $(basename "$f")"
    done
    # dc resume N: run again from phase N (the phases are idempotent).
    if [ -n "$from" ]; then
        [[ "$from" =~ ^[0-9]+$ ]] || die "usage: dc resume [PHASE]"
        ./guest-exec.sh dc "Set-Content -Path '$GUEST_WORK\\phase' -Value $from" || die "could not set the phase"
        log "phase set to $from"
    fi
    guest_run dc dc/guest/resume.ps1 "Work=$GUEST_WORK" \
        || die "could not start build-resume in the guest"
    log "build-resume started. Next: ./build.sh dc wait"
}

dc_verify() {
    local out s
    s=$(dc_status) || die "guest agent on $DC_VM does not answer"
    [ -n "$(json_get "done" <<<"$s")" ] \
        || die "DC provisioning is not DONE (phase $(json_get phase <<<"$s")). Run ./build.sh dc wait first"
    out=$(guest_run dc dc/guest/verify.ps1 "Work=$GUEST_WORK") \
        || die "dc verify could not query the guest: $out"
    python3 - "$out" "$DOMAIN" "$NETBIOS" "${SMB_ENCRYPT:-1}" <<'PY'
import json, sys
got = json.loads(sys.argv[1].strip().splitlines()[-1])
domain, netbios, enc = sys.argv[2], sys.argv[3], sys.argv[4] == "1"
checks = [
    ("AD domain", str(got["domain"]).lower() == domain.lower(), got["domain"]),
    ("_ldap._tcp SRV record", got["srv"], got["srv"]),
    ("dcdiag /q exit code 0", got["dcdiag"] == 0, got["dcdiag"]),
    ("share Homes$", got["share"], got["share"]),
    ("Homes$ EncryptData", got["encrypt"] == enc, got["encrypt"]),
    ("CA service CertSvc", got.get("ca") == "Running", got.get("ca")),
    ("CA templates Machine, User", {"Machine", "User"} <= set(got.get("templates") or []), got.get("templates")),
    ("autoenroll templates MLD-LinuxComputer, MLD-LinuxUser", {"MLD-LinuxComputer", "MLD-LinuxUser"} <= set(got.get("templates") or []), sorted(t for t in (got.get("templates") or []) if t.startswith("MLD-"))),
    ("web enrollment https /certsrv (401)", got.get("web") == 401, got.get("web")),
    ("central store ADMX (Samba, GNOME, Firefox, Chrome, Windows)", {"samba", "GNOME_Settings", "firefox", "mozilla", "chrome", "google", "windows"} <= set(got.get("admx") or []), got.get("admx")),
]
for u in got["users"]:
    n = u["name"]
    checks += [
        (f"{n}: home folder", u["dir"], u["dir"]),
        (f"{n}: folder owner", str(u["owner"]).lower() == f"{netbios}\\{n}".lower(), u["owner"]),
        (f"{n}: homeDirectory", str(u["home"]).lower().endswith(f"\\homes$\\{n}".lower()), u["home"]),
        (f"{n}: in Linux group", u["linux"], u["linux"]),
    ]
# Information only: certsrv and DCOM also work with the Public profile (firewall rules with profile Any).
if got.get("net") != ["DomainAuthenticated"]:
    print(f"  warn  network profile is {got.get('net')}, not DomainAuthenticated (Domain-only firewall rules do not apply)")
bad = 0
for name, ok, val in checks:
    print(f"  {'ok  ' if ok else 'FAIL'}  {name}: {val}")
    bad += not ok
sys.exit(1 if bad else 0)
PY
    local skew; skew=$(dc_skew) || die "cannot read the DC clock"
    if [ "$skew" -le 60 ]; then printf '  ok    DC clock skew %ss\n' "$skew"
    else printf '  FAIL  DC clock skew %ss\n' "$skew"; return 1; fi
}

# A RAM snapshot restores the guest clock of the snapshot time. Set it to host UTC after the revert.
dc_revert() {
    "${VIRSH[@]}" snapshot-revert "$DC_VM" "$SNAPSHOT" --running
    for _ in $(seq 1 30); do
        if GUEST_EXEC_TIMEOUT=30 ./guest-exec.sh dc "Set-Date -Date ([DateTimeOffset]::FromUnixTimeSeconds($(date -u +%s)).LocalDateTime) | Out-Null" >/dev/null 2>&1; then
            log "reverted $DC_VM to $SNAPSHOT, clock set (skew $(dc_skew)s)"
            return 0
        fi
        sleep 5
    done
    die "reverted to $SNAPSHOT, but could not set the DC clock"
}

# Sets the AD passwords on a built DC to the values in lab.env (after a change of lab.env).
# DSRM_PW is not changed: ntdsutil reads the new DSRM password only from an interactive prompt.
dc_set_passwords() {
    need_secrets ADMIN_PW LAB_USER_PW JOIN_PW
    guest_run dc dc/guest/set-passwords.ps1 "AdminPw=$ADMIN_PW" "LabUsers=${LAB_USER_LIST[*]}" \
        "LabUserPw=$LAB_USER_PW" "JoinUser=$JOIN_USER" "JoinPw=$JOIN_PW" \
        || die "could not set the passwords on the DC"
    log "AD passwords set from lab.env (Administrator, ${LAB_USER_LIST[*]}, $JOIN_USER). DSRM_PW is unchanged"
}

# dc_read_home_file USER FILE: a file in the home of USER, read on the DC (client verify).
dc_read_home_file() { ./guest-exec.sh dc "Get-Content 'C:\\Homes\\$1\\$2'"; }

# certsrv on the DC: HTTP status and IIS substatus, SSL setting, Windows authentication, firewall for TCP 80.
dc_certsrv_diag() { guest_run dc dc/guest/certsrv-diag.ps1; }

cmd_dc() {
    local sub="${1:-}"; shift || true
    case "$sub" in
        iso) dc_iso ;;
        set-passwords) dc_set_passwords ;;
        certsrv-diag) dc_certsrv_diag ;;
        vm) dc_vm ;;
        start) dc_start ;;
        wait) dc_wait ;;
        phase) dc_phase ;;
        log) dc_log "$@" ;;
        resume) dc_resume "$@" ;;
        verify) dc_verify ;;
        screenshot) screenshot_vm "$DC_VM" "${1:-$STAGE/dc-console.png}" ;;
        snapshot) snapshot_vm "$DC_VM" "$SNAPSHOT" ;;
        revert) dc_revert ;;
        destroy) destroy_vm "$DC_VM" "$@" ;;
        *) die "unknown: dc ${sub:-<nothing>} (try ./build.sh help)" ;;
    esac
}
