# Sourced by build.sh when IDP=freeipa: the FreeIPA server in the dc role (Fedora 45, same dc_* functions as lib/dc.sh).
# shellcheck shell=bash

IPA_STATE=/var/lib/mld-ipa
IPA_INSTALL_ISO="$STAGE/fedora-ipa-ks.iso"
IPA_PROV_ISO="$STAGE/ipa-provision.iso"

# Fetches, pins (first use) and checks the Fedora netinstall ISO. The client can use the same file.
ipa_media() {
    if [ ! -f "$FEDORA_ISO" ]; then fetch_one "$FEDORA_ISO" "$FEDORA_URL"; fetch_fedora_sums; fi
    if [ -z "$(sum_for "$(basename "$FEDORA_ISO")")" ]; then
        pin_media
        warn "new sums in checksums.sha256: commit the file"
    fi
    verify_one "$FEDORA_ISO" || die "$(basename "$FEDORA_ISO") not verified: do not use this file"
}

dc_iso() {
    need_secrets ADMIN_PW IPA_DM_PW LAB_USER_PW
    local v val
    # FreeIPA refuses passwords shorter than 8 characters (default password policy).
    for v in ADMIN_PW IPA_DM_PW LAB_USER_PW; do
        val="${!v}"
        [ "${#val}" -ge 8 ] || die "$v: FreeIPA needs at least 8 characters"
    done
    ipa_media
    local d="$STAGE/ipa-iso"
    rm -rf "$d"; mkdir -p "$d/provision"
    umask 077
    render ipa/ks.cfg.tmpl "$d/ks.cfg" ks
    {
        echo "# Generated by build.sh from lab.env. Do not edit the copy on the server."
        for v in DOMAIN REALM DC_FQDN DC_IP NET_GW REVERSE_ZONE LAB_USERS IDM_GROUP ADMIN_PW IPA_DM_PW LAB_USER_PW; do
            printf '%s=%q\n' "$v" "${!v}"
        done
        echo "NTP_POOL=pool.ntp.org"
    } > "$d/provision/config.env"
    cp ipa/provision/*.sh "$d/provision/"
    mkdir -p "$d/provision/policy"
    cp ipa/policy/*.json "$d/provision/policy/"
    cp ipa/mld-ipa-provision.service "$d/"
    cp client/mld/selinux/qemu-ga-run.sh "$d/"
    rm -f "$IPA_PROV_ISO"
    genisoimage -quiet -J -r -V IPAPROV -o "$IPA_PROV_ISO" "$d"
    umask 022
    chmod 600 "$IPA_PROV_ISO"
    log "ipa-provision.iso ready (contains lab secrets, stays in .stage/)"
    log "remastering $(basename "$FEDORA_ISO") with the kickstart boot entry"
    rm -f "$IPA_INSTALL_ISO"
    fedora_grub_patch "$FEDORA_ISO" IPAPROV ' inst.ks=hd:LABEL=IPAPROV:/ks.cfg inst.text console=ttyS0,115200n8'
    xorriso -indev "$FEDORA_ISO" -outdev "$IPA_INSTALL_ISO" \
        -map "$STAGE/fedora-grub-EFI_BOOT.cfg" /EFI/BOOT/grub.cfg \
        -map "$STAGE/fedora-grub-boot_grub2.cfg" /boot/grub2/grub.cfg \
        -boot_image any replay 2>&1 | tail -2
    log "fedora-ipa-ks.iso ready"
    iso_stamp dc
}

dc_eject_cdroms() {
    local t
    for t in $("${VIRSH[@]}" domblklist "$DC_VM" --details | awk '$2 == "cdrom" { print $3 }'); do
        "${VIRSH[@]}" change-media "$DC_VM" "$t" --eject --config >/dev/null 2>&1 || true
    done
}

dc_vm() {
    require_qemu_access
    pool_refresh
    vm_exists "$DC_VM" && die "VM '$DC_VM' exists: ./build.sh dc destroy first"
    require_no_orphan_disk "$DC_VM"
    require_nocow "$DC_VM"
    if ! iso_current dc "$IPA_INSTALL_ISO" "$IPA_PROV_ISO"; then
        log "server ISOs missing or older than their inputs: building them"
        dc_iso
    fi
    # libvirt makes internal snapshots of a pflash VM only with a qcow2 NVRAM (dc_stage takes a snapshot).
    local nv="$POOL_DIR/${DC_VM}_VARS.qcow2"
    rm -f "$nv"
    qemu-img convert -f raw -O qcow2 "$OVMF_VARS" "$nv"
    log "installing $DC_VM (FreeIPA on Fedora 45, ${DC_VCPUS} vCPU, ${DC_RAM_MB} MB, ${DC_DISK_GB} GB)."
    log "The install takes 10-30 min."
    # clock offset=utc: Kerberos rejects more than 5 min skew between the client and the server.
    virt-install \
        --connect "$LIBVIRT_URI" \
        --name "$DC_VM" \
        --machine q35 \
        --boot "loader=$OVMF_CODE,loader.readonly=yes,loader.type=pflash,loader.secure=yes,nvram=$nv" \
        --xml ./os/nvram/@format=qcow2 \
        --features smm.state=on \
        --vcpus "$DC_VCPUS" \
        --memory "$DC_RAM_MB" \
        --cpu host-passthrough \
        --disk "pool=$POOL,size=$DC_DISK_GB,bus=virtio,format=qcow2,driver.discard=unmap" \
        --network "network=$NET,model=virtio" \
        --cdrom "$IPA_INSTALL_ISO" \
        --disk "path=$IPA_PROV_ISO,device=cdrom,readonly=on" \
        --os-variant "${DC_OS_VARIANT:-$(pick_os_variant fedora45 fedora44 fedora-unknown linux2024 linux2022)}" \
        --clock offset=utc \
        --graphics vnc,listen=127.0.0.1 \
        --video virtio \
        --serial pty \
        --channel unix,target.type=virtio,target.name=org.qemu.guest_agent.0 \
        --noautoconsole \
        --noreboot \
        --wait "${DC_INSTALL_WAIT_MIN:-60}"
    "${VIRSH[@]}" domstate "$DC_VM" | grep -q 'shut off' \
        || die "$DC_VM still runs: the install did not finish. Check ./build.sh dc screenshot"
    dc_eject_cdroms
    "${VIRSH[@]}" autostart "$DC_VM" >/dev/null
    "${VIRSH[@]}" start "$DC_VM" >/dev/null
    log "$DC_VM installed and started. Next: ./build.sh dc wait"
}

dc_start() {
    require_qemu_access
    "${VIRSH[@]}" domstate "$DC_VM" | grep -q 'shut off' || die "$DC_VM is not shut off"
    "${VIRSH[@]}" start "$DC_VM" >/dev/null
    log "$DC_VM started. FreeIPA answers after approximately 1 min (./build.sh dc phase)"
}

dc_status() { GUEST_EXEC_TIMEOUT=30 guest_run dc ipa/guest/status.sh 2>/dev/null; }

dc_phase_name() {
    case "$1" in
        "") echo "0: not started" ;;
        1) echo "1: ipa-server-install (DNS, CA) for $DOMAIN" ;;
        2) echo "2: users, group $IDM_GROUP, host group, HBAC" ;;
        3) echo "3: NFS homes (sec=krb5p), automount maps" ;;
        4) echo "4: user certificate profile, CA ACL" ;;
        5) echo "5: policy endpoint /mld-policy" ;;
        *) echo "$1" ;;
    esac
}

dc_phase() {
    local s
    s=$(dc_status) || { echo "guest agent not reachable (install running or VM rebooting)"; return 0; }
    if [ -n "$(json_get failed <<<"$s")" ]; then echo "FAILED: $(json_get failed <<<"$s")"; return 0; fi
    if [ -n "$(json_get "done" <<<"$s")" ]; then echo "DONE ($(json_get "done" <<<"$s"))"; return 0; fi
    dc_phase_name "$(json_get phase <<<"$s")"
}

dc_log() { ./guest-exec.sh dc "tail -n ${1:-60} $IPA_STATE/provision.log"; }

dc_skew() {
    local s; s=$(dc_status) || return 1
    local skew=$(( $(json_get utc <<<"$s") - $(date -u +%s) ))
    echo "${skew#-}"
}

dc_wait() {
    local deadline=$(( $(date +%s) + 60*60 )) last="unset" s phase failed done_at skew
    log "waiting for the FreeIPA provisioning (up to 1 h)"
    while [ "$(date +%s)" -lt "$deadline" ]; do
        if "${VIRSH[@]}" domstate "$DC_VM" 2>/dev/null | grep -q 'shut off'; then
            warn "$DC_VM is shut off during provisioning: starting it"
            "${VIRSH[@]}" start "$DC_VM" >/dev/null 2>&1 || true
        fi
        if s=$(dc_status); then
            failed=$(json_get failed <<<"$s")
            if [ -n "$failed" ]; then
                warn "provisioning FAILED: $failed"
                dc_log 40 || true
                die "fix the cause, then ./build.sh dc resume [PHASE] (or dc destroy + dc vm)"
            fi
            done_at=$(json_get "done" <<<"$s")
            if [ -n "$done_at" ]; then
                skew=$(( $(json_get utc <<<"$s") - $(date -u +%s) )); skew=${skew#-}
                [ "$skew" -le 60 ] || die "server clock is ${skew}s off host UTC: Kerberos rejects more than 300s"
                log "FreeIPA provisioning DONE at $done_at (clock skew ${skew}s)"
                ./guest-exec.sh dc "cat $IPA_STATE/timing.log" 2>/dev/null | sed 's/^/  /' || true
                return 0
            fi
            phase=$(json_get phase <<<"$s")
            if [ "$phase" != "$last" ]; then printf '\n'; log "phase $(dc_phase_name "$phase")"; last="$phase"; fi
        fi
        printf '.'
        sleep 30
    done
    die "timed out. Check ./build.sh dc screenshot and ./build.sh dc log"
}

# After a boot, the provisioning marker is there before the IPA services answer.
dc_ready() {
    local i
    vm_exists "$DC_VM" || die "no VM '$DC_VM': ./build.sh dc vm first (about 30 min)"
    vm_running "$DC_VM" || dc_start
    dc_wait
    for i in $(seq 20); do
        GUEST_EXEC_TIMEOUT=30 ./guest-exec.sh dc 'ipactl status' >/dev/null 2>&1 && return 0
        [ "$i" -gt 1 ] || log "waiting for the IPA services on $DC_VM"
        sleep 15
    done
    die "the IPA services on $DC_VM do not answer after 5 min: ./build.sh dc log"
}

# dc resume [PHASE]: pushes the provision files and config.env from the current lab.env, then runs the phases again.
dc_resume() {
    local from="${1:-}" d="$STAGE/ipa-iso" snippet f
    [ -z "$from" ] || [[ "$from" =~ ^[0-9]+$ ]] || die "usage: dc resume [PHASE]"
    dc_iso >/dev/null
    snippet=$'set -e\numask 022'
    for f in "$d"/provision/0*.sh; do
        snippet+=$'\n'"echo '$(base64 -w0 "$f")' | base64 -d > /usr/local/lib/mld-ipa/$(basename "$f")"
    done
    snippet+=$'\n'"rm -rf /usr/local/lib/mld-ipa/policy; install -d -m 755 /usr/local/lib/mld-ipa/policy"
    for f in "$d"/provision/policy/*.json; do
        snippet+=$'\n'"echo '$(base64 -w0 "$f")' | base64 -d > /usr/local/lib/mld-ipa/policy/$(basename "$f")"
    done
    snippet+=$'\n'"echo '$(base64 -w0 "$d/provision/run.sh")' | base64 -d > /usr/local/sbin/mld-ipa-provision"
    snippet+=$'\n'"chmod 755 /usr/local/sbin/mld-ipa-provision"
    snippet+=$'\n'"(umask 077; echo '$(base64 -w0 "$d/provision/config.env")' | base64 -d > /etc/mld-ipa/config.env)"
    snippet+=$'\n'"restorecon -R /usr/local/sbin /usr/local/lib/mld-ipa /etc/mld-ipa"
    [ -z "$from" ] || snippet+=$'\n'"echo $from > $IPA_STATE/phase"
    snippet+=$'\n'"rm -f $IPA_STATE/FAILED $IPA_STATE/DONE
systemctl reset-failed mld-ipa-provision.service || true
systemctl restart --no-block mld-ipa-provision.service
echo 'mld-ipa-provision restarted'"
    ./guest-exec.sh dc "$snippet" || die "could not resume the provisioning on $DC_VM"
    log "provisioning restarted${from:+ from phase $from}. Next: ./build.sh dc wait"
}

dc_verify() {
    local out s
    s=$(dc_status) || die "guest agent on $DC_VM does not answer"
    [ -n "$(json_get "done" <<<"$s")" ] \
        || die "FreeIPA provisioning is not DONE (phase $(json_get phase <<<"$s")). Run ./build.sh dc wait first"
    out=$(guest_run dc ipa/guest/verify.sh "ADMIN_PW=$ADMIN_PW" "DOMAIN=$DOMAIN" "DC_FQDN=$DC_FQDN" \
        "LAB_USERS=$LAB_USERS" "IDM_GROUP=$IDM_GROUP") || die "dc verify could not query the server: $out"
    python3 - "$out" <<'PY'
import json, sys
got = json.loads(sys.argv[1].strip().splitlines()[-1])
def far(v):
    return len(v) >= 4 and v[:4].isdigit() and int(v[:4]) >= 2030
checks = [
    ("IPA services RUNNING (ipactl status)", got["running"] > 0 and got["stopped"] == 0,
     f"{got['running']} running, {got['stopped']} stopped"),
    ("_ldap._tcp SRV record", got["srv_ldap"] > 0, got["srv_ldap"]),
    ("_kerberos._udp SRV record", got["srv_kerberos"] > 0, got["srv_kerberos"]),
    ("HBAC allow_all disabled", got["allow_all"] == "FALSE", got["allow_all"]),
    ("HBAC mld-linux-login enabled", got["mld_hbac"] == "TRUE", got["mld_hbac"]),
    ("admin password does not expire soon", far(got["admin_expiration"]), got["admin_expiration"]),
    ("NFS export sec=krb5p", got["export"], got["export"]),
    ("nfs/ service key in /etc/krb5.keytab", got["nfs_keytab"], got["nfs_keytab"]),
    ("nfs-server + nfs-mountd active", got["nfs_units"].split() == ["active", "active"], got["nfs_units"]),
    ("automount key auto.home *", got["automount"], got["automount"]),
    ("certificate profile mldUserCert", got["profile"], got["profile"]),
    ("CA ACL mld-users", got["caacl"], got["caacl"]),
    ("policy endpoint without a ticket (401)", got["policy"] == "401", got["policy"]),
]
for u in got["users"]:
    n = u["name"]
    checks += [
        (f"{n}: password does not expire soon", far(u["expiration"]), u["expiration"]),
        (f"{n}: in the Linux group", u["member"] > 0, u["member"]),
        (f"{n}: NFS home owner and mode", u["home"] == f"{n} 700", u["home"]),
    ]
bad = 0
for name, ok, val in checks:
    print(f"  {'ok  ' if ok else 'FAIL'}  {name}: {val}")
    bad += not ok
sys.exit(1 if bad else 0)
PY
    local skew; skew=$(dc_skew) || die "cannot read the server clock"
    if [ "$skew" -le 60 ]; then printf '  ok    server clock skew %ss\n' "$skew"
    else printf '  FAIL  server clock skew %ss\n' "$skew"; return 1; fi
}

# A RAM snapshot restores the guest clock of the snapshot time. Set it to host UTC after the revert.
dc_revert() {
    "${VIRSH[@]}" snapshot-revert "$DC_VM" "$SNAPSHOT" --running
    for _ in $(seq 1 30); do
        if GUEST_EXEC_TIMEOUT=30 ./guest-exec.sh dc "date -u -s @$(date -u +%s) >/dev/null" >/dev/null 2>&1; then
            log "reverted $DC_VM to $SNAPSHOT, clock set (skew $(dc_skew)s)"
            return 0
        fi
        sleep 5
    done
    die "reverted to $SNAPSHOT, but could not set the server clock"
}

# dc_read_home_file USER FILE: a file in the home of USER, read on the server (client verify).
dc_read_home_file() { ./guest-exec.sh dc "cat /export/home/$1/$2"; }

cmd_dc() {
    local sub="${1:-}"; shift || true
    case "$sub" in
        iso) dc_iso ;;
        vm) dc_vm ;;
        start) dc_start ;;
        wait) dc_wait ;;
        phase) dc_phase ;;
        log) dc_log "$@" ;;
        resume) dc_resume "$@" ;;
        # Phase 5 is the last phase: resume from it publishes ipa/policy again and changes nothing else.
        policy) dc_resume 5 ;;
        verify) dc_verify ;;
        screenshot) screenshot_vm "$DC_VM" "${1:-$STAGE/dc-console.png}" ;;
        snapshot) snapshot_vm "$DC_VM" "$SNAPSHOT" ;;
        revert) dc_revert ;;
        destroy) destroy_vm "$DC_VM" "$@" ;;
        set-passwords|certsrv-diag) die "dc $sub: IDP=windows only" ;;
        *) die "unknown: dc ${sub:-<nothing>} (try ./build.sh help)" ;;
    esac
}
